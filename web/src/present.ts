import type { Kind, ProposedAction } from "./types";

export const KIND_ORDER: Kind[] = ["ratio_risk", "past_due_invoice", "stale_waitlist"];

export const KIND_LABEL: Record<Kind, string> = {
  ratio_risk: "Staffing",
  past_due_invoice: "Tuition",
  stale_waitlist: "Waitlist",
};

const LANGUAGES: Record<string, string> = { en: "English", es: "Spanish", so: "Somali", hmn: "Hmong" };

export function languageName(code: string | undefined): string | null {
  if (!code || code === "en") return null;
  return LANGUAGES[code] ?? code;
}

export function money(cents: number): string {
  return new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(cents / 100);
}

// Dates from the API are calendar days ("2026-10-20"); parse them as local days, not UTC midnight.
export function parseDay(day: string): Date {
  const [y, m, d] = day.split("-").map(Number);
  return new Date(y ?? 1970, (m ?? 1) - 1, d ?? 1);
}

export function shortDay(day: string): string {
  return parseDay(day).toLocaleDateString("en-US", { weekday: "short", month: "short", day: "numeric" });
}

export function longDay(day: string): string {
  return parseDay(day).toLocaleDateString("en-US", { weekday: "long", month: "long", day: "numeric" });
}

export function timeAgo(iso: string, now: Date = new Date()): string {
  const minutes = Math.round((now.getTime() - new Date(iso).getTime()) / 60_000);
  if (minutes < 1) return "just now";
  if (minutes < 60) return `${minutes} min ago`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return `${hours} hr ago`;
  const days = Math.round(hours / 24);
  return days === 1 ? "yesterday" : `${days} days ago`;
}

export function plural(n: number, word: string): string {
  return `${n} ${word}${n === 1 ? "" : "s"}`;
}

export function title(a: ProposedAction): string {
  switch (a.kind) {
    case "ratio_risk": {
      const short = a.facts.staff_required - a.facts.teaching_staff;
      return short > 0
        ? `${a.facts.classroom_name} needs ${plural(short, "more teacher")} on ${shortDay(a.facts.date)}`
        : `${a.facts.classroom_name} is over its group size on ${shortDay(a.facts.date)}`;
    }
    case "past_due_invoice":
      return `${money(a.facts.total_cents)} past due from ${a.facts.guardian_first_name}`;
    case "stale_waitlist":
      return `A ${a.facts.classroom_name} seat fits ${a.facts.child_first_name}`;
  }
}

export interface Fact {
  label: string;
  value: string;
}

export function facts(a: ProposedAction): Fact[] {
  switch (a.kind) {
    case "ratio_risk":
      return [
        { label: "Children expected", value: String(a.facts.expected_children) },
        { label: "Teachers scheduled", value: `${a.facts.teaching_staff} of ${a.facts.staff_required}` },
        { label: "Ratio", value: `1:${a.facts.ratio_applied} (${a.facts.mn_category})` },
        { label: "Group size limit", value: String(a.facts.group_size_limit) },
      ];
    case "past_due_invoice":
      return [
        { label: "Invoices", value: a.facts.invoice_numbers.join(", ") },
        { label: "Oldest due", value: shortDay(a.facts.oldest_due_on) },
        { label: "Days late", value: String(a.facts.max_days_past_due) },
      ];
    case "stale_waitlist":
      return [
        { label: "Age", value: `${a.facts.age_months} months` },
        { label: "Open seats", value: String(a.facts.open_seats) },
        { label: "Waiting", value: plural(a.facts.days_on_waitlist, "day") },
        {
          label: "Last contact",
          value: a.facts.days_since_contact === null ? "Never" : `${plural(a.facts.days_since_contact, "day")} ago`,
        },
        { label: "Wants to start", value: shortDay(a.facts.requested_start_on) },
      ];
  }
}

export function recipient(a: ProposedAction): string | null {
  return a.kind === "ratio_risk" ? null : a.facts.guardian_first_name;
}

// A plain starting point for the director to edit. Phase 4 replaces this with a Claude draft that
// cites the center's policies; until then nothing here is generated by a model.
export function starterMessage(a: ProposedAction, directorName: string, centerName: string): string {
  switch (a.kind) {
    case "past_due_invoice": {
      const f = a.facts;
      const invoices = f.invoice_numbers.length === 1 ? `invoice ${f.invoice_numbers[0]}` : `invoices ${f.invoice_numbers.join(", ")}`;
      return [
        `Hi ${f.guardian_first_name},`,
        `A quick note from ${centerName}: our records show ${money(f.total_cents)} open on ${invoices}, with the oldest due ${longDay(f.oldest_due_on)}.`,
        "If you've already sent it, thank you, and please ignore this. If a payment plan would help, reply here and we'll work something out.",
        `Thanks,\n${directorName}`,
      ].join("\n\n");
    }
    case "stale_waitlist": {
      const f = a.facts;
      return [
        `Hi ${f.guardian_first_name},`,
        `Good news from ${centerName}: we have an opening in our ${f.classroom_name} room that fits ${f.child_first_name}, and we could plan on a start around ${longDay(f.requested_start_on)}.`,
        "Are you still interested? Reply here and we'll hold the seat while we send enrollment paperwork.",
        `Warmly,\n${directorName}`,
      ].join("\n\n");
    }
    case "ratio_risk":
      return "";
  }
}

export interface SnoozeOption {
  label: string;
  until: Date;
}

function atEight(d: Date): Date {
  const out = new Date(d);
  out.setHours(8, 0, 0, 0);
  return out;
}

export function snoozeOptions(now: Date = new Date()): SnoozeOption[] {
  const tomorrow = atEight(new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1));
  const threeDays = atEight(new Date(now.getFullYear(), now.getMonth(), now.getDate() + 3));
  const daysToMonday = ((8 - now.getDay()) % 7) || 7;
  const monday = atEight(new Date(now.getFullYear(), now.getMonth(), now.getDate() + daysToMonday));
  return [
    { label: "Tomorrow morning", until: tomorrow },
    { label: "In 3 days", until: threeDays },
    { label: "Next Monday", until: monday },
  ];
}
